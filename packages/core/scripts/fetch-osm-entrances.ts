// Downloads Station entrance points from OpenStreetMap (© OpenStreetMap contributors, ODbL) into
// data-sources/osm-entrances.json, then writes src/data/entrances.ts. Run from packages/core:
// pnpm fetch-osm-entrances
// An entrance belongs to a Station only when an OSM stop area (public_transport=stop_area) lists both
// the entrance and that Station's OSM element. Entrances outside such a stop area are left out:
// nothing is matched by distance (owner, 2026-10-28: "show none rather than guessing").
import { readFileSync, writeFileSync } from "node:fs";
import { STATIONS } from "../src/data/stations.ts";

const EXTRACT = new URL("../data-sources/osm-entrances.json", import.meta.url);
const OUT = new URL("../src/data/entrances.ts", import.meta.url);
const BBOX = "14.40,120.90,14.80,121.20";
const QUERY = `[out:json][timeout:90];
node["railway"~"^(subway_entrance|train_station_entrance)$"](${BBOX});
out body;
rel["public_transport"="stop_area"](${BBOX});
out body;`;

interface OverpassElement {
  type: "node" | "way" | "relation";
  id: number;
  lat?: number;
  lon?: number;
  tags?: Record<string, string>;
  members?: { type: string; ref: number; role: string }[];
}

if (!process.argv.includes("--offline")) {
  const res = await fetch("https://overpass-api.de/api/interpreter", {
    method: "POST",
    headers: { "User-Agent": "LearnRT data script (github.com/Magzzi/learnrt-ph)" },
    body: new URLSearchParams({ data: QUERY }),
  });
  if (!res.ok) throw new Error(`Overpass: HTTP ${res.status}`);
  const json = (await res.json()) as { osm3s: { timestamp_osm_base: string }; elements: OverpassElement[] };
  const entrances = json.elements
    .filter((e) => e.type === "node")
    .map((e) => ({ osmId: `node/${e.id}`, lat: e.lat!, lng: e.lon!, ref: e.tags?.ref ?? null, name: e.tags?.name ?? null }))
    .sort((a, b) => a.osmId.localeCompare(b.osmId));
  const stopAreas = json.elements
    .filter((e) => e.type === "relation")
    .map((e) => ({ osmId: `relation/${e.id}`, members: e.members!.map((m) => `${m.type}/${m.ref}`) }))
    .sort((a, b) => a.osmId.localeCompare(b.osmId));
  const extract = {
    attribution: "© OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright)",
    osmBase: json.osm3s.timestamp_osm_base,
    query: QUERY,
    entrances,
    stopAreas,
  };
  writeFileSync(EXTRACT, JSON.stringify(extract, null, 2) + "\n");
}

// --offline regenerates src/data/entrances.ts from the committed extract.
const extract = JSON.parse(readFileSync(EXTRACT, "utf8")) as {
  osmBase: string;
  entrances: { osmId: string; lat: number; lng: number; ref: string | null; name: string | null }[];
  stopAreas: { osmId: string; members: string[] }[];
};
const byOsmId = new Map(extract.entrances.map((e) => [e.osmId, e]));
const stationByOsmId = new Map(STATIONS.filter((s) => s.osmId).map((s) => [s.osmId!, s.id]));

const linked: Record<string, typeof extract.entrances> = {};
for (const area of extract.stopAreas) {
  const stationIds = [...new Set(area.members.flatMap((m) => stationByOsmId.get(m) ?? []))];
  if (stationIds.length !== 1) continue; // No Station of ours, or more than one: not ours to decide.
  const entrances = area.members.flatMap((m) => byOsmId.get(m) ?? []);
  if (entrances.length > 0) (linked[stationIds[0]!] ??= []).push(...entrances);
}

const lines = Object.keys(linked)
  .sort()
  .map((id) => {
    const list = [...new Map(linked[id]!.map((e) => [e.osmId, e])).values()].sort((a, b) => a.osmId.localeCompare(b.osmId));
    return `  "${id}": [\n${list.map((e) => `    ${JSON.stringify({ osmId: e.osmId, location: { lat: e.lat, lng: e.lng }, ref: e.ref, name: e.name })},`).join("\n")}\n  ],`;
  });
writeFileSync(
  OUT,
  `// Generated by scripts/fetch-osm-entrances.ts from data-sources/osm-entrances.json. Do not edit.
// Entrances © OpenStreetMap contributors, ODbL. Unverified: see docs/data-todo.md D15.
import type { Entrance } from "../entrances";

export const OSM_ENTRANCES_BASE = "${extract.osmBase}";

export const ENTRANCES: Readonly<Record<string, readonly Entrance[]>> = {
${lines.join("\n")}
};
`,
);
console.log(`Linked ${Object.values(linked).flat().length} entrances to ${Object.keys(linked).length} Stations (OSM data as of ${extract.osmBase})`);
