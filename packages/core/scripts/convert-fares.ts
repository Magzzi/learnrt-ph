// Converts the website's fare matrices into src/data/fares.ts.
// Run from packages/core: pnpm convert-fares
import { readFileSync, writeFileSync } from "node:fs";
import * as XLSX from "xlsx";
import { STATIONS } from "../src/data/stations.ts";

const PUBLIC_DIR = new URL("../../../apps/web/public/", import.meta.url);
const OUT = new URL("../src/data/fares.ts", import.meta.url);

const TABLES = {
  "LRT1-sjt": { lineId: "LRT1", file: "LRT1-sjt-matrix.xlsx" },
  "LRT1-svf": { lineId: "LRT1", file: "LRT1-svf-matrix.xlsx" },
  "LRT2-sjt": { lineId: "LRT2", file: "LRT2-sjt-matrix.xlsx" },
  "LRT2-svf": { lineId: "LRT2", file: "LRT2-svf-matrix.xlsx" },
  "MRT3-regular": { lineId: "MRT3", file: "MRT3-matrix.xlsx" },
  "MRT3-discounted-sjt": { lineId: "MRT3", file: "MRT3-discounted-matrix.xlsx" },
} as const;

function stationId(lineId: string, name: string): string {
  const station = STATIONS.find((s) => s.lineId === lineId && s.name === name);
  if (!station) throw new Error(`No ${lineId} Station named "${name}"`);
  return station.id;
}

const entries = Object.entries(TABLES).map(([key, { lineId, file }]) => {
  const workbook = XLSX.read(readFileSync(new URL(file, PUBLIC_DIR)));
  const rows = XLSX.utils.sheet_to_json<unknown[]>(workbook.Sheets[workbook.SheetNames[0]!]!, { header: 1 });
  const names = rows[0]!.slice(1) as string[];
  const stationIds = names.map((name) => stationId(lineId, name));
  const fares = names.map((name, r) => {
    const row = rows[r + 1]!;
    if (row[0] !== name) throw new Error(`${file}: row ${r + 1} is "${row[0]}", expected "${name}"`);
    return names.map((_, c) => (typeof row[c + 1] === "number" ? row[c + 1] : null));
  });
  const fareRows = fares.map((row) => `      [${row.map(String).join(", ")}],`).join("\n");
  return `  ${JSON.stringify(key)}: {
    lineId: "${lineId}",
    sourceFile: "${file}",
    stationIds: ${JSON.stringify(stationIds)},
    fares: [
${fareRows}
    ],
  },`;
});

writeFileSync(
  OUT,
  `// Generated by scripts/convert-fares.ts from apps/web/public/*-matrix.xlsx. Do not edit by hand.
// Values are unverified: see docs/data-todo.md.
import type { FareTable } from "../fares";

export const FARE_TABLES: Record<string, FareTable> = {
${entries.join("\n")}
};
`,
);
console.log(`Wrote ${entries.length} fare tables to ${OUT.pathname}`);
